function verify(parent, entries; seed = 42)
	Random.seed!(seed)
	nodes = sort(collect(keys(parent)))
	root = only(k for k in nodes if parent[k] === nothing)
	adj = Dict(k => vcat([c for c in nodes if parent[c] == k], parent[k] === nothing ? Int[] : [parent[k]]) for k in nodes)
	m = Dict(k => rand(1:3) for k in nodes)
	n = Dict(k => rand(1:3) for k in nodes)
	ρ = Dict((i, j) => rand(1:3) for i in nodes for j in adj[i])   # ρ[(i,j)] = dim of state on edge i -> j

	Inp   = Dict((k, j) => randn(ρ[(k, j)], n[k]) for k in nodes for j in adj[k])          # Inp^k_j
	Out   = Dict((k, i) => randn(m[k], ρ[(i, k)]) for k in nodes for i in adj[k])          # Out^k_i
	Trans = Dict((k, i, j) => (i == j ? ZeroMatrix(ρ[(k, i)], ρ[(j, k)]) : randn(ρ[(k, i)], ρ[(j, k)]))
	             for k in nodes for i in adj[k] for j in adj[k])                            # Trans^k_{i,j}
	D     = Dict(k => randn(m[k], n[k]) for k in nodes)

	spinners = [Spinner{Float64}(k, adj[k],
	                [Trans[(k, i, j)] for i in adj[k], j in adj[k]],
	                [Inp[(k, j)] for j in adj[k]],
	                [Out[(k, i)] for i in adj[k]],
	                D[k]) for k in nodes]
	T = TQSMatrix(spinners)
	A = Matrix(T, construct_tree(T.adjacency_list, root))
	blk(i, j) = A[T.mrange[i], T.nrange[j]]

	# paper nomenclature with respect to the root
	B(k, j) = Inp[(k, j)]; P(k, j) = Inp[(k, j)]
	U(k, i, j) = Trans[(k, i, j)]; V(k, i, j) = Trans[(k, i, j)]; W(k, i, j) = Trans[(k, i, j)]
	C(k, i) = Out[(k, i)]; Q(k, i) = Out[(k, i)]

	F = entries(B, P, U, V, W, C, Q, D)
	@assert length(F) == length(nodes)^2
	return maximum(norm(F[(i, j)] - blk(i, j)) / max(norm(blk(i, j)), 1) for i in nodes, j in nodes)
end

